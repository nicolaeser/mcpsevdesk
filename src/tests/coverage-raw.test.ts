describe("catalog stays curated", () => {
  it("keeps the minimized catalog tools", () => {
    for (const name of KEEP_TOOLS) {
      expect(TOOL_NAMES).toContain(name);
    }
  });

  it("does not register dropped tools", () => {
    for (const name of DROP_TOOLS) {
      expect(TOOL_NAMES).not.toContain(name);
    }
  });

  it("is exactly the minimized KEEP catalog", () => {
    expect([...TOOL_NAMES].sort()).toEqual([...KEEP_TOOLS].sort());
  });

  it("keeps the few unique endpoints that have no curated twin", () => {
    expect(TOOL_NAMES).toContain("sevdesk_get_bookkeeping_system_version");
    expect(TOOL_NAMES).toContain("sevdesk_get_documents");
    expect(TOOL_NAMES).toContain("sevdesk_get_communication_way_keys");
  });
});
